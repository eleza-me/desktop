for token, pair in tokens["color"].items():
    name = camel(token)
    lines.append(f"{(name + ':').ljust(width)} {resolve(pair['light']).ljust(9)} | {resolve(pair['dark']).ljust(9)}; // {token}")
lines += ["", "// ---- desktop additions"]
