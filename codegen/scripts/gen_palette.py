for name, light, dark, comment in EXTRA:
    lines.append(f"{(name + ':').ljust(width)} {resolve(light).ljust(9)} | {resolve(dark).ljust(9)}; // {comment}")
lines.append("")
out_path.write_text("\n".join(lines), encoding="utf-8")
