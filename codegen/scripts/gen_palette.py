def camel(token: str) -> str:
    parts = re.split(r"[/\-\s]+", token)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def resolve(value: str) -> str:
    value = value.strip()
    m = re.fullmatch(r"\{(.+)\}", value)
    if m:
        value = primitives[m.group(1)]
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})(?:@(\d+))?", value)
    if not m:
        raise SystemExit(f"bad color value: {value}")
    rgb = m.group(1).upper()
    if m.group(2) is None:
        return "#" + rgb
    alpha = round(int(m.group(2)) * 255 / 100)
    return "#%s%02X" % (rgb, alpha)


