QString Country::name() const {
	return IsPersian() ? nameFa : nameEn;
}

const std::vector<Country> &Countries() {
	static const auto result = [] {
		auto list = std::vector<Country>();
		list.reserve(sizeof(kRows) / sizeof(kRows[0]));
		for (const auto &row : kRows) {
			list.push_back(Country{
				QString::fromLatin1(row.code),
				QString::fromLatin1(row.iso),
				QString::fromUtf8(row.fa),
				QString::fromLatin1(row.en),
			});
		}
		return list;
	}();
	return result;
}

const Country *CountryByIso(const QString &iso) {
	const auto upper = iso.toUpper();
	for (const auto &country : Countries()) {
		if (country.iso == upper) {
			return &country;
		}
	}
	return nullptr;
}

const Country *CountryByCode(const QString &code) {
	const Country *first = nullptr;
	for (const auto &country : Countries()) {
		if (country.code != code) {
			continue;
		} else if (country.iso == QStringLiteral("IR")
			|| country.iso == QStringLiteral("US")) {
			return &country;
		} else if (!first) {
			first = &country;
		}
	}
	return first;
}

const Country *CountryByPhone(const QString &digits) {
	auto clean = Latinize(digits);
	if (clean.startsWith(QLatin1Char('+'))) {
		clean.remove(0, 1);
	}
	for (auto length = 4; length >= 1; --length) {
		if (clean.size() < length) {
			continue;
		}
		if (const auto found = CountryByCode(clean.left(length))) {
			return found;
		}
	}
	return nullptr;
}

std::vector<const Country*> SearchCountries(const QString &query) {
	auto result = std::vector<const Country*>();
	auto needle = Latinize(query.trimmed()).toLower();
	if (needle.startsWith(QLatin1Char('+'))) {
		needle.remove(0, 1);
	}
	for (const auto &country : Countries()) {
		if (needle.isEmpty()
			|| country.nameFa.contains(needle)
			|| country.nameEn.toLower().contains(needle)
			|| country.iso.toLower() == needle
			|| country.code.startsWith(needle)) {
			result.push_back(&country);
		}
	}
	return result;
}

QString FlagEmoji(const QString &iso) {
	auto result = QString();
	for (const auto ch : iso.toUpper()) {
		const auto code = ch.unicode();
		if (code < 'A' || code > 'Z') {
			return QString();
		}
		const auto point = char32_t(0x1F1E6 + (code - 'A'));
		result.append(QChar::fromUcs4(point));
	}
	return result;
}

bool FlagEmojiSupported() {
#ifdef Q_OS_WIN
	return false;
#else // Q_OS_WIN
	return true;
#endif // Q_OS_WIN
}

QString FlagOrIso(const QString &iso) {
	return FlagEmojiSupported() ? FlagEmoji(iso) : iso.toUpper();
}

